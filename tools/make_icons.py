"""Convert the Lucide icon set (ISC, https://lucide.dev; SVGs vendored in assets/icons_src/) into
  * python/icon_paths.py - flattened polylines on the 24 grid; the GUI strokes them on a tk.Canvas, which Tk draws at the
    screen's full (Retina) resolution, so they stay sharp (a Tk image is only ever 1 px = 1 pt and gets up-scaled);
  * assets/icons/<name>[_w].png - 16 px rasters for tk.Menu entries, which cannot hold a canvas.
Needs cairosvg and svg.path (dev only).  Run:  .venv/bin/python tools/make_icons.py"""
import io
import re
import math
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import cairosvg
from svg.path import Arc, Close, Move, parse_path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "assets" / "icons_src", ROOT / "assets" / "icons"
PX = 16                      # shown at 16 pt; Tk maps 1 image px to 1 pt
STROKE = 2.25                # in 24-unit grid -> 1.5 px at 16 px
INK, WHITE = "#0c0c0c", "#ffffff"

# app icon name -> lucide icon
MAP = {
    "add": "plus", "close": "x", "check": "check", "remove": "minus", "folder": "folder",
    "folder_add": "folder-plus", "image_in": "image-down", "reset": "rotate-ccw", "save": "save",
    "load": "folder-open", "trash": "trash-2", "edit": "pencil", "export": "upload", "stop": "square",
    "select_all": "square-check-big", "select_none": "square-minus", "compare": "columns-2",
    "fit": "scan", "gear": "settings", "look": "layout-grid", "source": "folder-input", "border": "frame",
    "size": "scaling", "brand_logo": "image", "camera": "camera", "lens": "circle-dot", "focal": "ruler",
    "aperture": "aperture", "shutter": "timer", "iso": "gauge", "exposure": "sliders-horizontal",
    "date": "calendar-days", "text": "type", "clean": "list-x",
    "chevron_right": "chevron-right", "chevron_down": "chevron-down", "updown": "chevrons-up-down",
}


def render(svg_text, color, px):
    svg = svg_text.replace("currentColor", color)
    svg = re.sub(r'stroke-width="[^"]*"', 'stroke-width="%s"' % STROKE, svg, count=1)
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=px * 4, output_height=px * 4)
    return Image.open(io.BytesIO(png)).convert("RGBA").resize((px, px), Image.LANCZOS)


def _pts(c):
    return (round(c.real, 3), round(c.imag, 3))


def flatten(svg_text):
    """Polylines (lists of (x, y) on the 24 grid) for every shape of a Lucide SVG."""
    root = ET.fromstring(re.sub(r"<!--.*?-->", "", svg_text, flags=re.S))
    out = []
    for el in root.iter():
        tag = el.tag.split("}")[-1]
        a = el.attrib
        f = lambda k, d=0.0: float(a.get(k, d))
        if tag == "path":
            cur = []
            for seg in parse_path(a["d"]):
                if isinstance(seg, Move):
                    if len(cur) > 1:
                        out.append(cur)
                    cur = [_pts(seg.end)]
                    continue
                if isinstance(seg, Close):
                    if cur:
                        cur.append(cur[0])
                    continue
                n = 2 if seg.__class__.__name__ == "Line" else 10
                cur += [_pts(seg.point(i / (n - 1))) for i in range(1, n)]
            if len(cur) > 1:
                out.append(cur)
        elif tag == "circle":
            cx, cy, r = f("cx"), f("cy"), f("r")
            out.append([(round(cx + r * math.cos(t * math.tau / 48), 3), round(cy + r * math.sin(t * math.tau / 48), 3))
                        for t in range(49)])
        elif tag == "line":
            out.append([(f("x1"), f("y1")), (f("x2"), f("y2"))])
        elif tag == "polyline":
            v = [float(x) for x in re.split(r"[ ,]+", a["points"].strip())]
            out.append(list(zip(v[0::2], v[1::2])))
        elif tag == "rect":
            x, y, w, h = f("x"), f("y"), f("width"), f("height")
            r = min(f("rx", a.get("ry", 0)), w / 2, h / 2)
            pts = []
            for cx, cy, a0 in ((x + w - r, y + r, -90), (x + w - r, y + h - r, 0), (x + r, y + h - r, 90),
                               (x + r, y + r, 180)):
                for i in range(7 if r else 1):
                    t = math.radians(a0 + 90 * i / 6)
                    pts.append((round(cx + r * math.cos(t), 3), round(cy + r * math.sin(t), 3)))
            pts.append(pts[0])
            out.append(pts)
    return out


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    paths = {}
    n = 0
    for name, lucide in MAP.items():
        text = (SRC / (lucide + ".svg")).read_text()
        render(text, INK, PX).save(OUT / (name + ".png"))
        render(text, WHITE, PX).save(OUT / (name + "_w.png"))
        n += 2
        paths[name] = flatten(text)
    mod = ROOT / "python" / "icon_paths.py"
    lines = ['"""Generated by tools/make_icons.py from Lucide (ISC) - do not edit."""', "", "ICON_PATHS = {"]
    for name, polys in paths.items():
        lines.append("    %r: %r," % (name, [[list(p) for p in poly] for poly in polys]))
    lines.append("}")
    mod.write_text("\n".join(lines) + "\n")
    print("wrote", n, "files to", OUT)


if __name__ == "__main__":
    sys.exit(main())
